## test-banner.R -- banner.R (M1.4c): 48 colunas, ASCII, ANSI so com always (CONTROL: auto sem TTY/Windows), regra de exibicao.
library(testthat)
local({
  e <- pc_source_lib("banner")
  for (n in ls(e, all.names = TRUE)) assign(n, get(n, e), envir = globalenv())
})
ver <- trimws(readLines(file.path(pc_root(), "config", "VERSION"), n = 1L, warn = FALSE))
mk <- function(color = "never", format = "text") list(color = color, format = format, version = ver)
has_esc <- function(b) grepl(paste0(intToUtf8(27L), "["), paste(b, collapse = ""), fixed = TRUE)

test_that("curva com exatamente 48 colunas, ASCII, deterministica", {
  b <- prevcarga_banner(mk())
  expect_type(b, "character")
  expect_match(b[1], "prevcarga", fixed = TRUE)
  expect_equal(length(b), 8L)
  expect_true(all(nchar(b[2:7], type = "bytes") == 48L))
  expect_match(b[8], ver, fixed = TRUE)
  expect_equal(ver, readLines(file.path(pc_root(), "config", "VERSION"), warn = FALSE)[1])
  expect_true(all(utf8ToInt(paste(b, collapse = "")) <= 127L))
  expect_identical(b, prevcarga_banner(mk()))
  src <- readBin(file.path(pc_root(), "scripts", "lib", "banner.R"), "raw", 1e5)
  expect_true(all(as.integer(src) <= 127L))
})

test_that("ESC so com always e auto+TTY+unix; CONTROL auto sem TTY e Windows", {
  expect_false(has_esc(prevcarga_banner(mk("never"), tty = TRUE, os = "unix")))
  expect_true(has_esc(prevcarga_banner(mk("always"), tty = FALSE, os = "windows")))
  expect_false(has_esc(prevcarga_banner(mk("auto"), tty = FALSE, os = "unix")))
  expect_false(has_esc(prevcarga_banner(mk("auto"), tty = TRUE, os = "windows")))
  expect_true(has_esc(prevcarga_banner(mk("auto"), tty = TRUE, os = "unix")))
  expect_true(prevcarga_use_color(mk("always"), FALSE, "windows"))
  expect_false(prevcarga_use_color(mk("auto"), FALSE, "unix"))
  expect_false(prevcarga_use_color(mk("auto"), TRUE, "windows"))
  expect_true(prevcarga_use_color(mk("auto"), TRUE, "unix"))
  b <- prevcarga_banner(mk("always"))
  expect_false(has_esc(b[c(1, 8)]))
  expect_true(all(utf8ToInt(paste(b, collapse = "")) <= 127L))
})

test_that("regra de exibicao por verbo/formato", {
  expect_true(prevcarga_banner_wanted(mk(), "--help"))
  expect_true(prevcarga_banner_wanted(mk(), "--version"))
  expect_true(prevcarga_banner_wanted(mk(), NULL))
  expect_true(prevcarga_banner_wanted(mk(), "doctor"))
  expect_false(prevcarga_banner_wanted(mk(format = "json"), "doctor"))
  expect_false(prevcarga_banner_wanted(mk(format = "json"), "--help"))
  expect_false(prevcarga_banner_wanted(mk(), "models"))
  expect_false(prevcarga_banner_wanted(mk(), "status"))
})
